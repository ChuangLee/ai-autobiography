"""Fit the film's small relief figure to the same aligned scan as the portrait shot.

The field is an outer envelope of measured horizontal head sections. Three
10-bit radial measurements share each word read by the original marcher.
"""
import argparse
from pathlib import Path
import struct

import numpy as np
from scipy.optimize import least_squares

COLS, ROWS = 96, 73
SCALE = np.array([.515, .485, -.480])
OFFSET = np.array([0., 2.12-.08*.485, -.102])


def aligned_mesh(path):
    data = path.read_bytes()
    magic, count, nindex = struct.unpack_from("<4sII", data)
    if magic != b"LPS3":
        raise ValueError("expected the aligned LPS3 surface from pack_sitter.py")
    xyz = np.ndarray((count, 3), dtype="<i2", buffer=data, offset=12, strides=(14, 2))
    triangles = np.frombuffer(data, dtype="<u2", count=nindex, offset=12+14*count).reshape(-1, 3)
    return (xyz / 10000 * SCALE + OFFSET)[triangles]


def section(mesh, y):
    cuts = mesh[(mesh[:, :, 1].min(1) < y) & (mesh[:, :, 1].max(1) >= y)]
    a, b = cuts, np.roll(cuts, -1, axis=1)
    crossing = (a[:, :, 1] < y) != (b[:, :, 1] < y)
    p, q = a[crossing], b[crossing]
    t = (y-p[:, 1]) / (q[:, 1]-p[:, 1])
    return (p[:, [0, 2]] + t[:, None]*(q[:, [0, 2]]-p[:, [0, 2]])).reshape(-1, 2, 2)


def radii(segments, center, rays):
    a = segments[:, 0] - center
    d = segments[:, 1] - segments[:, 0]
    cross = rays[:, 0, None]*d[:, 1] - rays[:, 1, None]*d[:, 0]
    den = np.where(abs(cross) > 1e-11, cross, np.inf)
    r = (a[:, 0]*d[:, 1] - a[:, 1]*d[:, 0]) / den
    t = (a[:, 0]*rays[:, 1, None] - a[:, 1]*rays[:, 0, None]) / den
    return np.max(np.where((t >= -1e-8) & (t <= 1+1e-8) & (r >= 0), r, 0), axis=1)


def samples(mesh, rows, angles):
    ymin = -1.28*SCALE[1]+OFFSET[1]
    ymax = float(mesh[:, :, 1].max())
    levels = np.linspace(ymin, ymax, rows)
    angles = 2*np.pi * np.arange(angles)/angles
    rays = np.stack([np.sin(angles), -np.cos(angles)], axis=1)
    centers, surface = [], []
    for y in levels:
        seg = section(mesh, min(y, ymax-.00025))
        # The scan includes the shoulders. The film already has a collar and
        # shoulders, so tuck only the bottom of the nape inside that neckline.
        if y < 1.76:
            low = np.clip((1.76-y)/.30, 0, 1)
            rear = np.clip((seg[:, :, 1]+.12)/.22, 0, 1)
            tuck = .59 * (low*low*(3-2*low)) * (rear*rear*(3-2*rear))
            neck = np.array([.005, .055])
            seg = neck + (seg-neck) * (1-tuck[:, :, None])
        points = seg.reshape(-1, 2)
        middle = (points.max(0) + points.min(0))*.5
        centers.append(middle)
        surface.append(radii(seg, middle, rays))
    return levels, np.array(centers), np.array(surface)


def crown_fit(mesh, peak):
    p = np.unique(mesh.reshape(-1,3), axis=0)
    p = p[p[:,1] > peak-.21]
    def residual(c):
        x,z,rx,rz,ry,tilt_x,tilt_z=c
        h=p[:,1]-peak
        xx=(p[:,0]-x-tilt_x*h)/rx
        zz=(p[:,2]-z-tilt_z*h)/rz
        return xx*xx+zz*zz+((h+ry)/ry)**2-1
    return least_squares(residual,[.01,.045,.355,.43,.42,0,0],
                         bounds=([-.1,-.1,.16,.18,.20,-.7,-.7],[.1,.2,.65,.75,.80,.7,.7])).x


def write(path, levels, centers, surface, crown):
    def literal(value):
        return "%.7f" % value
    def vec(values):
        return "vec%df(%s)"%(len(values),",".join(map(literal,values)))
    radial=np.rint(surface*2046).astype(np.uint32)
    if radial.max() > 1023:
        raise ValueError("radial envelope exceeds the 10-bit range")
    words=radial[:,::3]|(radial[:,1::3]<<10)|(radial[:,2::3]<<20)
    wordlist=["0x%08xu"%v for v in words.flat]
    blocks=[",".join(wordlist[i:i+8]) for i in range(0,len(wordlist),8)]
    xc,zc,rx,rz,ry,tx,tz=crown
    path.write_text("// Generated by tools/fit_sitter_shell.py from the CC BY 3.0 Lee Perry-Smith scan.\n"
                    "// Attribution and reproduction instructions: scan-source.txt.\n"
                    "export const shellData = `\n"
                    f"const sitterFloor={levels[0]:.7f};\nconst sitterCrown={levels[-1]:.7f};\n"
                    f"const sitterRows={len(centers)};\nconst sitterColumns={surface.shape[1]};\n"
                    f"const sitterCrownCenter={vec([xc,levels[-1]-ry,zc])};\n"
                    f"const sitterCrownRadii={vec([rx,ry,rz])};\nconst sitterCrownTilt={vec([tx,tz])};\n"
                    f"const sitterAxis=array<vec2f,{len(centers)}>(\n"+",\n".join(map(vec,centers))+");\n"
                    f"const sitterRadial=array<u32,{len(wordlist)}>(\n"+",\n".join(blocks)+");\n`;\n")


def fit(source, output):
    mesh=aligned_mesh(source)
    levels,centers,surface=samples(mesh,ROWS,COLS)
    rounded=np.rint(surface*2046)/2046
    print("measured cross sections",surface.shape,"maximum radius quantization error",np.max(abs(rounded-surface)))
    write(output,levels,centers,surface,crown_fit(mesh,levels[-1]))


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input",type=Path);parser.add_argument("output",type=Path)
    args=parser.parse_args();fit(args.input,args.output)
